/// GF(2^8) 乘 x 的多项式（xtime）。
#[inline]
fn xtime(a: u8) -> u8 {
    ((a << 1) ^ (if a & 0x80 != 0 { 0x1b } else { 0 })) & 0xff
}

/// 密钥轮数：AES-128 → 10，AES-192 → 12，AES-256 → 14。
#[inline]
fn rounds_for(key_len: usize) -> usize {
    match key_len {
        16 => 10,
        24 => 12,
        32 => 14,
        _ => 10, // 仅支持 16/24/32；调用方保证长度合法
    }
}

/// 密钥扩展（FIPS 197 5.2），返回 4*(rounds+1) 个 32 位字。
fn key_expansion(key: &[u8]) -> [u32; 60] {
    let nk = key.len() / 4;
    let nr = rounds_for(key.len());
    let total = 4 * (nr + 1);
    let mut w = [0u32; 60];
    for i in 0..nk {
        w[i] = u32::from_be_bytes([key[4 * i], key[4 * i + 1], key[4 * i + 2], key[4 * i + 3]]);
    }
    let mut rcon: u32 = 1;
    let mut i = nk;
    while i < total {
        let mut temp = w[i - 1];
        if i % nk == 0 {
            // RotWord + SubWord + Rcon
            temp = temp.rotate_left(8);
            temp = sub_word(temp) ^ (rcon << 24);
            rcon = xtime(rcon as u8) as u32;
        } else if nk > 6 && i % nk == 4 {
            temp = sub_word(temp);
        }
        w[i] = w[i - nk] ^ temp;
        i += 1;
    }
    w
}

fn sub_word(x: u32) -> u32 {
    let b = x.to_be_bytes();
    u32::from_be_bytes([SBOX[b[0] as usize], SBOX[b[1] as usize], SBOX[b[2] as usize], SBOX[b[3] as usize]])
}

/// 用 AES 加密一个分组。`key` 长度 16/24/32。
pub fn encrypt_block(key: &[u8], block: &[u8; 16]) -> [u8; 16] {
    let w = key_expansion(key);
    let nr = rounds_for(key.len());
    let mut s = *block;
    add_round_key(&mut s, &w, 0);
    for round in 1..nr {
        sub_bytes(&mut s);
        shift_rows(&mut s);
        mix_columns(&mut s);
        add_round_key(&mut s, &w, round);
    }
    sub_bytes(&mut s);
    shift_rows(&mut s);
    add_round_key(&mut s, &w, nr);
    s
}

/// 用 AES 解密一个分组。`key` 长度 16/24/32。
pub fn decrypt_block(key: &[u8], block: &[u8; 16]) -> [u8; 16] {
    let w = key_expansion(key);
    let nr = rounds_for(key.len());
    let mut s = *block;
    add_round_key(&mut s, &w, nr);
    for round in (1..nr).rev() {
        inv_shift_rows(&mut s);
        inv_sub_bytes(&mut s);
        add_round_key(&mut s, &w, round);
        inv_mix_columns(&mut s);
    }
    inv_shift_rows(&mut s);
    inv_sub_bytes(&mut s);
    add_round_key(&mut s, &w, 0);
    s
}

fn add_round_key(s: &mut [u8; 16], w: &[u32; 60], round: usize) {
    for c in 0..4 {
        let word = w[4 * round + c];
        let b = word.to_be_bytes();
        for r in 0..4 {
            // 状态布局 s[4*c + r] = state[row r][col c]；密钥字按列异或。
            s[4 * c + r] ^= b[r];
        }
    }
}

fn sub_bytes(s: &mut [u8; 16]) {
    for b in s.iter_mut() {
        *b = SBOX[*b as usize];
    }
}

fn inv_sub_bytes(s: &mut [u8; 16]) {
    for b in s.iter_mut() {
        *b = INV_SBOX[*b as usize];
    }
}

fn shift_rows(s: &mut [u8; 16]) {
    let t = *s;
    for r in 1..4 {
        for c in 0..4 {
            s[4 * c + r] = t[4 * ((c + r) % 4) + r];
        }
    }
}

fn inv_shift_rows(s: &mut [u8; 16]) {
    let t = *s;
    for r in 1..4 {
        for c in 0..4 {
            s[4 * c + r] = t[4 * ((c + 4 - r) % 4) + r];
        }
    }
}

fn mix_columns(s: &mut [u8; 16]) {
    for c in 0..4 {
        let a = [s[4 * c], s[4 * c + 1], s[4 * c + 2], s[4 * c + 3]];
        s[4 * c] = xtime(a[0]) ^ (xtime(a[1]) ^ a[1]) ^ a[2] ^ a[3];
        s[4 * c + 1] = a[0] ^ xtime(a[1]) ^ (xtime(a[2]) ^ a[2]) ^ a[3];
        s[4 * c + 2] = a[0] ^ a[1] ^ xtime(a[2]) ^ (xtime(a[3]) ^ a[3]);
        s[4 * c + 3] = (xtime(a[0]) ^ a[0]) ^ a[1] ^ a[2] ^ xtime(a[3]);
    }
}

fn inv_mix_columns(s: &mut [u8; 16]) {
    // 每行系数轮换：{0e,0b,0d,09} 循环右移。
    const COEF: [[u8; 4]; 4] = [
        [0x0e, 0x0b, 0x0d, 0x09],
        [0x09, 0x0e, 0x0b, 0x0d],
        [0x0d, 0x09, 0x0e, 0x0b],
        [0x0b, 0x0d, 0x09, 0x0e],
    ];
    for c in 0..4 {
        let a = [s[4 * c], s[4 * c + 1], s[4 * c + 2], s[4 * c + 3]];
        for r in 0..4 {
            let mut v: u8 = 0;
            for k in 0..4 {
                v ^= mul_byte(a[k], COEF[r][k]);
            }
            s[4 * c + r] = v;
        }
    }
}

/// 通用 GF(2^8) 乘法（多项式模 x^8+x^4+x^3+x+1）。
fn mul_byte(a: u8, b: u8) -> u8 {
    let mut result: u8 = 0;
    let mut x = a;
    let mut y = b;
    for _ in 0..8 {
        if y & 1 != 0 {
            result ^= x;
        }
        let hi = x & 0x80;
        x <<= 1;
        if hi != 0 {
            x ^= 0x1b;
        }
        y >>= 1;
    }
    result
}

