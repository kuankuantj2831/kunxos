#[no_mangle]
pub extern "C" fn k_main(_argc: usize, argv: *const usize) -> usize {
    print("[stub] starting\n");
    extract_name(argv);

    if !fb_init() {
        print("[stub] /dev/fb0 mmap failed, no framebuffer\n");
        unsafe { exit(1); }
    }
    print("[stub] framebuffer ");
    print_dec(unsafe { FB_W } as u32);
    print("x");
    print_dec(unsafe { FB_H } as u32);
    print(" mapped\n");

    render();
    flip();
    print("[stub] ready\n");

    loop {
        let (click, moved) = poll_input();
        if moved {
            render();
            flip();
        }
        if let Some((x, y)) = click {
            print("[stub] tap (");
            print_dec(x as u32);
            print(",");
            print_dec(y as u32);
            print(")\n");
            if back_hit(x, y) {
                print("[stub] back -> exit\n");
                break;
            }
        }
        if poll_key() {
            print("[stub] ESC -> exit\n");
            break;
        }
        sleep_ms(16);
    }

    print("[stub] exiting\n");
    unsafe { exit(0); }
}

// ==================== helpers ====================

fn print_dec(mut v: u32) {
    if v == 0 {
        print("0");
        return;
    }
    let mut buf = [0u8; 12];
    let mut i = buf.len();
    while v > 0 {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
    }
    unsafe { write_fd(1, &buf[i..]); }
}

