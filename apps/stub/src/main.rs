// KunxOS stub app: placeholder UI for apps without a full implementation.
//
// Launched by the launcher via fork + execve; argv[0] is the path (e.g.
// /bin/phone). The basename becomes the app name, shown on a full-screen
// "coming soon" placeholder. Tap the top-left back button or press ESC to
// exit (exit(0)); the launcher reaps it and redraws the desktop.
//
// Behaves like the other GUI apps: draws directly to /dev/fb0, double
// buffered, mouse cursor follows pointer.

