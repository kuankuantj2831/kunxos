/// 二分查找码点，返回字形索引。
#[inline]
pub fn cjk_index(cp: u16) -> Option<usize> {
    let mut lo = 0usize;
    let mut hi = CJK_CODES.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let v = CJK_CODES[mid];
        if v == cp {
            return Some(mid);
        } else if v < cp {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    None
}

/// 解码 `s[i..]` 处的下一个 UTF-8 码点，返回 `(码点, 字节数)`。
/// `i` 越界或非法字节时返回 `(0, 1)`（渲染为空位）。
#[inline]
pub fn utf8_next(s: &[u8], i: usize) -> (u32, usize) {
    if i >= s.len() {
        return (0, 1);
    }
    let b0 = s[i];
    if b0 < 0x80 {
        return (b0 as u32, 1);
    }
    let need = if b0 >= 0xF0 {
        4
    } else if b0 >= 0xE0 {
        3
    } else if b0 >= 0xC0 {
        2
    } else {
        return (0, 1);
    };
    if i + need > s.len() {
        return (0, 1);
    }
    let mut cp = match need {
        2 => (b0 & 0x1F) as u32,
        3 => (b0 & 0x0F) as u32,
        _ => (b0 & 0x07) as u32,
    };
    for k in 1..need {
        let b = s[i + k];
        if b & 0xC0 != 0x80 {
            return (0, 1);
        }
        cp = (cp << 6) | (b & 0x3F) as u32;
    }
    (cp, need)
}

/// 字符串的文本宽度（单位：像素，ASCII 8px、CJK 16px）。
#[inline]
pub fn text_width(s: &[u8]) -> i32 {
    let mut w = 0i32;
    let mut i = 0;
    while i < s.len() {
        let (cp, n) = utf8_next(s, i);
        if cp >= 0x80 {
            w += CJK_W;
        } else {
            w += 8;
        }
        i += n;
    }
    w
}
